import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const script=fs.readFileSync(new URL('../../services/jrip-server/ui/output-layout.js',import.meta.url),'utf8');
const geometry=vm.runInNewContext(script.slice(script.indexOf(' function geometry('),script.indexOf(' function render('))+';geometry');
const a4={widthMicrons:210000,heightMicrons:297000};
let g=geometry({width:2480,height:3508},a4,300);assert.equal(g.mismatch,false);assert(Math.abs(g.widthPercent-100)<.1);
g=geometry({width:3508,height:2480},a4,300);assert.equal(g.mismatch,true);assert(g.widthPercent>100&&g.heightPercent<100);
g=geometry({width:1240,height:1754},a4,300);assert.equal(g.mismatch,true);assert(Math.abs(g.widthPercent-50)<.1);
g=geometry({width:2481,height:3508},a4,300);assert.equal(g.mismatch,false);
g=geometry({width:2482,height:3508},a4,300);assert.equal(g.mismatch,true);
g=geometry({width:2480,height:3508,resolution:{x:[600,1],y:[300,1]}},a4,300);assert.equal(g.mismatch,true);
assert.equal(geometry({width:1,height:1},a4,0),null);
assert.equal(geometry({width:1,height:1},{widthMicrons:0,heightMicrons:1},300),null);
console.log('PASS: paper proportions, landscape overflow, undersize, one-pixel tolerance, DPI mismatch, invalid dimensions');
const place={scaleMode:'fit',scaleBasisPoints:10000,rotation:0,alignX:1,alignY:1,offsetXMicrons:0,offsetYMicrons:0};
g=geometry({width:2,height:3},{widthMicrons:400,heightMicrons:400},254,place);assert(Math.abs(g.widthPercent-75)<.001);assert.equal(g.leftPercent,25);assert.equal(g.topPercent,0);assert.equal(g.clipped,false);
g=geometry({width:2,height:3},{widthMicrons:300,heightMicrons:200},254,{...place,scaleMode:'actual',rotation:90});assert.equal(g.widthPercent,100);assert.equal(g.heightPercent,100);
g=geometry({width:2,height:3},{widthMicrons:200,heightMicrons:300},254,{...place,scaleMode:'actual',alignX:0,alignY:0,offsetXMicrons:-100});assert.equal(g.leftPercent,-50);assert.equal(g.clipped,true);
console.log('PASS: quantized placement agrees with Rust golden vectors');
